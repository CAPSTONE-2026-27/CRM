package com.techcrm.crm.sap;

import lombok.Getter;
import lombok.Setter;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.stereotype.Component;

import java.time.Duration;

/**
 * Connection details for SAP Build Process Automation.
 *
 * All of these come from a service key created against the Process Automation
 * instance in the SAP BTP cockpit. None of them belongs in a committed file:
 * the defaults here are blank, and a blank client id disables the integration
 * rather than failing at start-up, so the application runs unchanged on a
 * machine that has no SAP access.
 */
@Component
@ConfigurationProperties(prefix = "sap.process")
@Getter
@Setter
public class SapProcessProperties {

    /**
     * Master switch. Off by default.
     *
     * With this false the validation endpoints still work — they return a pass
     * with a warning — so the lead flow behaves exactly as it did before this
     * feature existed. Turning it on is a deliberate act.
     */
    private boolean enabled = false;

    /** OAuth token endpoint from the service key ("url" + /oauth/token). */
    private String tokenUrl = "";

    /** Service key clientid. */
    private String clientId = "";

    /** Service key clientsecret. Never commit a real value. */
    private String clientSecret = "";

    /** Base URL of the workflow REST API from the service key ("endpoints"). */
    private String apiBaseUrl = "";

    /** Definition id of the lead validation process, as the platform shows it. */
    private String leadValidationDefinitionId = "";

    /**
     * The environment a deployed process lives in, when the platform needs
     * telling.
     *
     * Some landscapes scope the workflow API to one environment per request
     * and answer "definition not found" without this, while listing no
     * definitions at all. Others infer it from the service key and reject an
     * unexpected parameter. Blank by default so it is sent only where it is
     * needed, which is a property of the tenant rather than of this
     * application.
     */
    private String environmentId = "";

    /**
     * The trigger's API key, sent as {@code irpa-api-key}.
     *
     * Separate from the OAuth credentials and required in addition to them:
     * the token says which tenant is calling, this says which trigger is being
     * invoked. A tenant that does not want it leaves this blank and no header
     * is sent.
     */
    private String apiKey = "";

    /**
     * Definition id of the proposal generation process.
     *
     * Blank by default, and a blank one means a deal reaching that stage starts
     * nothing — the document can still be generated by hand. Wiring a bot to a
     * stage is a deliberate act, not something that happens because the
     * platform credentials were filled in.
     */
    private String proposalDefinitionId = "";

    /** Definition id of the contract generation process. Blank disables it,
     *  for the same reason as above. */
    private String contractDefinitionId = "";

    /**
     * Definition id of the opportunity creation process.
     *
     * Blank means a lead is converted by the CRM itself, as it was before this
     * bot existed. Only a configured one hands the job to the automation.
     */
    private String opportunityDefinitionId = "";

    /**
     * Definition id of the meeting scheduler process, which invites a lead to
     * a meeting a representative has booked.
     *
     * Blank means the meeting is recorded and nobody is told — which is worth
     * saying out loud rather than failing, since the booking itself is still
     * useful to the representative.
     */
    /**
     * Definition id of the process that invites a lead to a meeting.
     *
     * Separate from the deal one because the two invitations say different
     * things: this one welcomes an enquiry to a first conversation, while the
     * other discusses an opportunity that already exists. Splitting them also
     * keeps each process's inputs to what its own invitation needs, rather
     * than declaring both sets and leaving half of them empty.
     */
    private String meetingSchedulerDefinitionId = "";

    /** Definition id of the process that invites a converted lead to a meeting
     *  about their deal. */
    private String dealMeetingSchedulerDefinitionId = "";

    /**
     * Definition id of the lead welcome process, which emails a new lead.
     *
     * Blank means no welcome is sent, which is how this ships — an email to a
     * customer is not something to start happening because platform
     * credentials were filled in.
     */
    private String leadWelcomeDefinitionId = "";

    /**
     * What each process calls its recipient inputs.
     *
     * The platform matches context keys against the declared process inputs
     * exactly and refuses anything else, so these have to be whatever the
     * deployed process says — which is the process author's choice, not ours.
     * The defaults are the obvious spelling; a process that chose another one
     * is still a working process, and reading the name from here is a better
     * answer than re-releasing someone else's project to rename a variable.
     */
    private String contractRecipientNameKey = "recipientname";
    private String contractRecipientEmailKey = "recipientemail";
    private String proposalRecipientNameKey = "recipientname";
    private String proposalRecipientEmailKey = "recipientemail";

    /**
     * How long a validation may take before the caller stops waiting.
     *
     * Twenty seconds against a process measured in single-digit seconds. The
     * budget exists because the alternative — waiting indefinitely — means an
     * outage in a cloud service prevents a representative from capturing a
     * lead at all.
     */
    private Duration validationTimeout = Duration.ofSeconds(20);

    /** How often the backend asks the platform whether an instance has
     *  finished. Short enough that the browser sees the answer promptly,
     *  long enough not to hammer the API. */
    private Duration pollInterval = Duration.ofSeconds(2);

    /** Per-call timeout for the platform's own HTTP endpoints. */
    private Duration requestTimeout = Duration.ofSeconds(10);

    /** Configured when every value the integration needs is present. Checked
     *  rather than assumed, so a half-filled configuration behaves like an
     *  absent one instead of failing on the first lead. */
    public boolean isConfigured() {
        return enabled
                && notBlank(tokenUrl)
                && notBlank(clientId)
                && notBlank(clientSecret)
                && notBlank(apiBaseUrl);
    }

    /**
     * Whether the lead validation bot in particular can run.
     *
     * Separate from {@link #isConfigured}, which answers only whether the
     * platform itself can be reached. Each bot is deployed on its own schedule
     * — one may exist while another has not been built yet — and a missing
     * definition id must disable that bot alone, not the connection every
     * other bot shares.
     */
    public boolean isLeadValidationConfigured() {
        return isConfigured() && notBlank(leadValidationDefinitionId);
    }

    private static boolean notBlank(String value) {
        return value != null && !value.isBlank();
    }
}
