package com.techcrm.crm.deal;

import com.techcrm.crm.sap.SapProcessProperties;
import com.techcrm.crm.sap.SapProcessTriggerClient;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.scheduling.annotation.Async;
import org.springframework.stereotype.Component;
import org.springframework.transaction.event.TransactionPhase;
import org.springframework.transaction.event.TransactionalEventListener;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Starts a document bot when a deal reaches the stage that calls for one.
 *
 * Reaching Proposal means the customer is owed a quotation; reaching Contract
 * means they are owed an agreement. Both documents were already generated by an
 * automation calling this API — what was missing was anything telling it when.
 * The stage change is that signal.
 *
 * <b>After the commit, never during it.</b> The automation's first act is to
 * call back and ask this CRM for the deal. Started inside the transaction that
 * moved it, that call would read the stage as it was before — or the move could
 * roll back afterwards, leaving a contract for a stage that never happened.
 *
 * <b>Off the representative's thread.</b> Dragging a card between columns must
 * not wait on a cloud platform in another region.
 *
 * <b>Safe to fire twice.</b> Generation is idempotent: a second run for the
 * same deal returns the document the first one produced rather than making
 * another, and the send returns ALREADY_SENT rather than emailing the customer
 * again. Without that this would be far too dangerous to automate.
 */
@Component
public class DealStageBotTrigger {

    private static final Logger log = LoggerFactory.getLogger(DealStageBotTrigger.class);

    private final SapProcessTriggerClient sap;
    private final SapProcessProperties properties;

    public DealStageBotTrigger(SapProcessTriggerClient sap, SapProcessProperties properties) {
        this.sap = sap;
        this.properties = properties;
    }

    @Async
    @TransactionalEventListener(phase = TransactionPhase.AFTER_COMMIT)
    public void onStageChanged(DealStageChanged event) {
        String definitionId = definitionFor(event.stage());
        if (definitionId == null || definitionId.isBlank()) {
            // Either a stage no bot answers, or one whose bot is not configured
            // on this installation. Both are ordinary.
            return;
        }

        String instanceId = sap.startProcess(definitionId, contextFor(event));

        if (instanceId == null) {
            // The document can still be generated by hand, and the deal has
            // already moved. Worth a line in the log, not worth an alarm.
            log.warn("Could not start the {} bot for deal {}", event.stage(), event.dealId());
            return;
        }
        log.info("Started the {} bot for deal {} as instance {}",
                event.stage(), event.dealId(), instanceId);
    }

    /**
     * The context a bot expects, under the names its process declares.
     *
     * Lower case throughout, because the platform stores process input names
     * that way and matches them exactly — a camel-cased key is reported as a
     * missing property rather than being quietly normalised.
     *
     * Every declared input is sent, including the two left empty: the platform
     * validates the context against the whole set and refuses one that omits a
     * property, rather than defaulting it. Empty is what the automation reads
     * as "no override", which is what an unattended run wants — the document
     * goes to the account's own contact, not to an address someone typed while
     * testing by hand.
     *
     * The recipient keys are configurable because the name is the deployed
     * process's to choose, not ours. A process that spells them differently is
     * still a working process, and re-releasing someone else's project to
     * correct a spelling is a worse answer than reading the name from
     * configuration.
     */
    private Map<String, Object> contextFor(DealStageChanged event) {
        boolean proposal = DealStages.PROPOSAL.equals(event.stage());

        Map<String, Object> context = new LinkedHashMap<>();
        context.put("dealid", String.valueOf(event.dealId()));
        context.put(proposal
                ? properties.getProposalRecipientNameKey()
                : properties.getContractRecipientNameKey(), "");
        context.put(proposal
                ? properties.getProposalRecipientEmailKey()
                : properties.getContractRecipientEmailKey(), "");
        return context;
    }

    private String definitionFor(String stage) {
        if (DealStages.PROPOSAL.equals(stage)) {
            return properties.getProposalDefinitionId();
        }
        if (DealStages.CONTRACT.equals(stage)) {
            return properties.getContractDefinitionId();
        }
        return null;
    }
}
